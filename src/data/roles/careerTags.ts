const AWP_SET = new Set<string>(AWPERS);
const IGL_SET = new Set<string>(IGLS);
const RIFLE_SET = new Set<string>(RIFLERS);

export function careerTagFor(playerId: string): CareerTag {
	return mergeCareerTags(
		AWP_SET.has(playerId) ? { awp: true } : {},
		IGL_SET.has(playerId) ? { igl: true } : {},
		RIFLE_SET.has(playerId) ? { rifle: true } : {},
	);
}

export function mergeCareerTags(...tags: CareerTag[]): CareerTag {
	const merged: CareerTag = {};
	if (tags.some((tag) => tag.awp)) merged.awp = true;
	if (tags.some((tag) => tag.igl)) merged.igl = true;
	if (tags.some((tag) => tag.rifle)) merged.rifle = true;
	return merged;
}

export function isCareerAwper(tag: CareerTag): boolean {
	return tag.awp === true;
}

export function isCareerIgl(tag: CareerTag): boolean {
	return tag.igl === true;
}
